# 工作列拿來認「這個視窗屬於哪支程式」的身分（`pdf2ppt_gui_2.py` 的
# `set_app_user_model_id()`；沒有它，工作列會沿用啟動鏈上游那支 wscript 的圖示）。
# ⚠️ **`tools/make_shortcut.py` 會把這個值寫進 .lnk，兩邊必須同值**——那顆捷徑正是
# 工作列拿圖示的地方；不同值的話，釘選到工作列的那顆與執行中的視窗會變成兩個各自
# 獨立的按鈕，而且**不會有任何錯誤訊息**。改這裡就要重跑那支腳本。
# ⚠️ 與姊妹專案 MP4-2-SRT 的 `VincentLiang.MP4-2-SRT` 刻意不同：同一個字串會讓兩支
# 程式在工作列上併成一顆按鈕。
APP_ID = "VincentLiang.NotebookLM.Pdf2Ppt"

# 視窗標題列那一行，也是桌面與「開始」功能表那顆捷徑顯示的名字
# （`tools/make_shortcut.py` 的 `install_to`），以及執行紀錄的檔頭。
# ⚠️ 它是**純顯示**：改成別的中文完全不影響磁碟。與 `APP_DIR_NAME` 的區分見下面。
# ⚠️ 「啟動.vbs」的訊息框標題是這個名字的**短版手抄**（VBScript 讀不到 Python，那
# 支又必須在環境還沒建起來時就能講話）——改名字要順手改它，`tests/test_docs.py`
# 的 `test_the_launcher_message_box_uses_the_app_name` 釘著。
APP_TITLE = "NotebookLM PDF → PPT 轉檔工具"

# 視窗第一句：這支程式是做什麼的。標題列寫的是**名字**，名字說不出它做什麼——所以
# 整個視窗只此一句用途說明，坐在卡片之外、10pt 粗體淡色字（`Sub.Muted.TLabel`）。
# 舊版這裡上面還有一行與標題列一字不差的 15pt 大標題，2026-08-25 拿掉了。
APP_SUB = "把 NotebookLM 產出繁中 PDF 簡報，本機轉換成可編輯的 PowerPoint。"

# 滑鼠停在桌面圖示上會看到的那句（`tools/make_shortcut.py` 寫進 .lnk 的 description）。
# ⚠️ **與 `APP_SUB` 講的是同一件事，但刻意分成兩句、不合併**（姊妹專案 MP4-2-SRT
# 合併成一句，那是它的處境）：這一句是在**程式還沒開起來**的時候被讀到的——桌面上
# 一顆圖示，旁邊沒有任何其他畫面，所以它得把「會不會上傳」直接講完（那是使用者最
# 常問的第一個問題）。`APP_SUB` 坐在視窗裡，底下就是「本機」跑的整組控制項，不必
# 再解釋一次。⚠️ 合併的代價是其中一邊要跟著改口，那是使用者看得到的字。
APP_DESC = "把 NotebookLM 的簡報 PDF 轉成可編輯的 PowerPoint（全程在這台電腦上跑，不會上傳）"

# 這支工具在 `%LOCALAPPDATA%` 底下的資料夾名（目前只有皮膚快取掛在它底下，見
# `pdf2ppt/paths.py` 的 `appdata_root`）。⚠️ **改它等於叫使用者的快取整批失效**
# （舊的還在原處，但再也沒有人去看它），所以它實際上是個對外承諾——`README.md`
# 把這個名字寫給使用者看過。
#
# ⚠️ **`APP_DIR_NAME`、`APP_TITLE`、`APP_ID` 是三個概念，字面值哪天撞在一起也不可以
# 併成一份**：這一個是**落地位置**（改了要使用者重畫一次快取）、`APP_TITLE` 是**純
# 顯示**（改成別的中文完全不影響磁碟）、`APP_ID` 是**工作列拿來認應用程式的身分**
# （改了釘選的那顆會跟執行中的視窗分家）。併成一份的話，哪天把標題改掉就會順手把
# 快取搬家——資產還在磁碟上、程式卻說沒有，**兩個位置都存在**，連「檔案不見了」都
# 不會發生。姊妹專案 MP4-2-SRT 三者同值是巧合，不是設計（在那邊寫「這個字串只能有
# 一份」的測試會當場紅）。
APP_DIR_NAME = "NotebookLM_Pdf2Ppt"
